	glm_logistic_dataset.train(x=x_var, y=target_var, training_frame=h2o_dataset, model_id=model_id)
	# glm_logistic_dataset.train(x=features_h2o_dataset, y=target_var, training_frame=h2o_dataset, model_id="glm_logistic_dataset")
	glm_logistic_dataset.auc(xval=True)
	return glm_logistic_dataset


